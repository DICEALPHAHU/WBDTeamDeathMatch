package alphahu.tdm.game;

/**
 * 一场死斗比赛的生命周期。
 *
 * <pre>
 *   WAITING ──(人数达标)──▶ COUNTDOWN ──▶ LIVE ──(达成击杀目标 / 时间耗尽)──▶ ENDED
 *      ▲                                                                      │
 *      └────────────────(自动重开 / 管理员重置 / 人走光)──────────────────────┘
 * </pre>
 *
 * <p>与爆破模式最大的不同是没有回合：一场比赛就是一次完整的对抗，
 * 期间玩家阵亡后不断复活，直到分出胜负为止。
 *
 * @author AlphaHu
 */
public enum MatchState {

    /** 有人在场但还没开始：玩家待在大厅，等人齐或等管理员开。 */
    WAITING,

    /** 开局倒计时。此阶段不允许造成伤害，给玩家就位的时间。 */
    COUNTDOWN,

    /** 比赛进行中：可击杀、可复活、可计分。 */
    LIVE,

    /** 已分出胜负，正在展示结算，走完延时后重开或清场。 */
    ENDED
}
